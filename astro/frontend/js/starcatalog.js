// Galactic plane: 180 points at b=0, l=0..355 deg
// Precomputed RA/Dec pairs [ra_deg, dec_deg]
// Generated from IAU galactic coordinate transformation
export const GALACTIC_EQUATOR = (() => {
  // NGP: ra=192.85948 dec=27.12825, ascending node l0=32.93192 (all degrees)
  const NGP_RA = 192.85948 * Math.PI / 180;
  const NGP_DEC = 27.12825 * Math.PI / 180;
  const L0 = 32.93192 * Math.PI / 180;
  const pts = [];
  for (let li = 0; li <= 360; li += 3) {
    const l = li * Math.PI / 180;
    const b = 0;
    const sinDec = Math.sin(b) * Math.sin(NGP_DEC) +
                   Math.cos(b) * Math.cos(l - L0) * Math.cos(NGP_DEC);
    const dec = Math.asin(Math.max(-1, Math.min(1, sinDec)));
    const y = Math.cos(b) * Math.sin(l - L0);
    const x = Math.sin(b) * Math.cos(NGP_DEC) - Math.cos(b) * Math.cos(l - L0) * Math.sin(NGP_DEC);
    let ra = Math.atan2(y, x) + NGP_RA;
    if (ra < 0) ra += 2 * Math.PI;
    if (ra > 2 * Math.PI) ra -= 2 * Math.PI;
    pts.push([ra * 180 / Math.PI, dec * 180 / Math.PI]);
  }
  return pts;
})();

